-- The rendered table definition. No server and no driver: given what JDBC
-- reported, this is the CREATE TABLE and the notes written under it.
local support = require("tests.support")
local check = support.check
local detail = require("neogrip.explorer.detail")

local function render(driver, details)
	local connection = { id = "t", driver = driver }
	return detail.render(connection, { connection = connection, schema = "public" }, "users", details)
end

local FULL = {
	remarks = "One row per person who can sign in.",
	rows = {
		{ name = "id", type = "bigint", nullable = false, is_pk = true, auto_increment = true },
		{ name = "email", type = "varchar(255)", nullable = false, remarks = "Login address." },
		{ name = "note", type = "text", nullable = true, default_expr = "''::text" },
		{ name = "search", type = "tsvector", nullable = true, generated = true },
	},
	primary_key = { "id" },
	primary_key_name = "users_pkey",
	indexes = {
		-- The index that implements the key, which the constraint already says.
		{ name = "users_pkey", unique = true, columns = { "id" } },
		{ name = "users_email_key", unique = true, columns = { "email" } },
		{ name = "users_email_idx", unique = false, columns = { "email" } },
		{
			name = "users_recent",
			unique = false,
			columns = { "created_at", "id" },
			order = { "desc", "asc" },
			filter = "note <> ''",
		},
	},
	foreign_keys = {
		{
			name = "users_org_fk",
			schema = "public",
			table = "orgs",
			columns = { "org_id" },
			ref_columns = { "id" },
			on_delete = "cascade",
			on_update = "no action",
		},
	},
	referenced_by = {
		{
			name = "orders_user_fk",
			schema = "public",
			table = "orders",
			columns = { "id" },
			ref_columns = { "user_id" },
		},
	},
}

support.describe("detail: the rendered definition")

local lines = render("postgres", FULL)
local text = table.concat(lines, "\n")

check("opens with a qualified CREATE TABLE", lines[1], 'CREATE TABLE "public"."users" (')
check("every column is named and typed", text:find('"email"%s+varchar%(255%)') ~= nil, true)
check("NOT NULL is carried over", text:find('"id"%s+bigint%s+NOT NULL') ~= nil, true)
check("so is a default", text:find("DEFAULT ''::text", 1, true) ~= nil, true)
check("the primary key is a constraint, not a column flag", text:find('PRIMARY KEY %("id"%)') ~= nil, true)
check("named, when the server named it", text:find('CONSTRAINT "users_pkey"%s+PRIMARY KEY') ~= nil, true)
check(
	"a column the server fills in says which kind it is",
	text:find("GENERATED BY DEFAULT AS IDENTITY", 1, true) ~= nil,
	true
)
check("and a computed one is marked without inventing its expression", text:find("generated") ~= nil, true)
check(
	"an outbound key references its target",
	text:find('FOREIGN KEY %("org_id"%)') ~= nil and text:find('REFERENCES "public"."orgs" %("id"%)') ~= nil,
	true
)
check("carrying the action the server will take", text:find("ON DELETE CASCADE", 1, true) ~= nil, true)
-- NO ACTION is the default, so saying it is noise in a definition you read.
check("but not the action that is merely the default", text:find("ON UPDATE", 1, true), nil)
check("the statement is closed", text:find("\n);", 1, true) ~= nil, true)

support.describe("detail: what is written underneath")

-- An index is a statement, not a note about one: the whole point of this
-- buffer is that what is not a comment can be run.
check(
	"an index is written as the statement that would create it",
	text:find('CREATE INDEX "users_email_idx" ON "public"."users" %("email"%);') ~= nil,
	true
)
check(
	"a unique one says so",
	text:find('CREATE UNIQUE INDEX "users_email_key" ON "public"."users" %("email"%);') ~= nil,
	true
)
check(
	"the index that implements the key is left out, because the constraint is it",
	text:find('INDEX "users_pkey"', 1, true),
	nil
)
check("a descending column keeps its direction", text:find('"created_at" DESC', 1, true) ~= nil, true)
check("and an ascending one is not spelled out", text:find('"id" ASC', 1, true), nil)
check("a partial index keeps its condition", text:find("WHERE note <> ''", 1, true) ~= nil, true)
check(
	"a remark becomes the statement that sets it",
	text:find('COMMENT ON TABLE "public"."users" IS \'One row per person who can sign in.\';', 1, true) ~= nil,
	true
)
check(
	"on a column too",
	text:find('COMMENT ON COLUMN "public"."users"."email" IS \'Login address.\';', 1, true) ~= nil,
	true
)
check("inbound references are counted", text:find("-- Referenced by (1)", 1, true) ~= nil, true)
check(
	"and read as that table pointing at this one",
	text:find('"public"."orders" %("user_id"%) %-> %("id"%)') ~= nil,
	true
)

-- The invariant this file exists to protect: a buffer you might yank out of
-- must not hand back statements the server never produced. So everything that
-- is not a comment has to be a statement, which here means it ends in a
-- semicolon or is part of one that continues.
local notes, statements = 0, 0
for _, line in ipairs(lines) do
	if line:find("^%-%-") then
		notes = notes + 1
	elseif vim.trim(line) ~= "" then
		statements = statements + 1
	end
end
check("there are notes", notes > 0, true)
check("and real statements beside them", statements > 0, true)
check(
	"nothing runnable is left dangling",
	(function()
		local runnable = {}
		for _, line in ipairs(lines) do
			if not line:find("^%-%-") and vim.trim(line) ~= "" then
				runnable[#runnable + 1] = line
			end
		end
		-- Strip the trailing comment an index kind may carry, then insist the
		-- last line of the whole lot closes a statement.
		local last = runnable[#runnable]:gsub("%s*%-%-.*$", "")
		return vim.trim(last):sub(-1)
	end)(),
	";"
)

support.describe("detail: an engine with no indexes or keys")

local bare = render("trino", {
	rows = { { name = "ticket_jira", type = "varchar", nullable = true } },
	primary_key = {},
	indexes = {},
	foreign_keys = {},
	referenced_by = {},
})
local bare_text = table.concat(bare, "\n")
check("the table still renders", bare[1], 'CREATE TABLE "public"."users" (')
check("no PRIMARY KEY is invented", bare_text:find("PRIMARY KEY"), nil)
check("and the absence is stated", bare_text:find("No indexes, foreign keys", 1, true) ~= nil, true)

support.describe("detail: nothing to render")

local empty = render("postgres", { rows = {} })
check("a table with no columns says so, rather than emitting a broken statement", #empty, 1)
check("as a comment", empty[1]:find("^%-%-") ~= nil, true)

support.describe("detail: the buffer it opens")

local function open(driver, context, table_name)
	local connection = { id = "__test_detail__", driver = driver }
	context = vim.tbl_extend("force", { connection = connection }, context)
	return detail.open(connection, context, table_name, { ("-- %s"):format(table_name) })
end

-- The window the definition lands in is the one you were working in. It used
-- to split, so every visit to a table stacked another window.
local origin = vim.api.nvim_create_buf(true, false)
vim.api.nvim_set_current_buf(origin)
local windows_before = #vim.api.nvim_list_wins()

local bufnr = open("postgres", { catalog = "testdb", schema = "public" }, "users")
check("it is in this window", vim.api.nvim_get_current_buf(), bufnr)
check("which did not split", #vim.api.nvim_list_wins(), windows_before)
check("the buffer you came from is the alternate, so <C-^> goes back", vim.fn.bufnr("#"), origin)
check(
	"named after the table",
	vim.api.nvim_buf_get_name(bufnr),
	"neogrip://table/__test_detail__/testdb/public/users"
)
check("read-only", vim.bo[bufnr].readonly, true)
check("and highlighted as sql", vim.bo[bufnr].filetype, "sql")
check("no keymap is planted in the document (ADR-0017)", vim.fn.maparg("q", "n", false, true).buffer, nil)

local again = open("postgres", { catalog = "testdb", schema = "public" }, "users")
check("opening it again is the same buffer", again, bufnr)
check("in the same single window", #vim.api.nvim_list_wins(), windows_before)

-- A name is one segment per part, kept even when a part does not apply: an
-- engine with no catalog (mysql) or with neither catalog nor schema (sqlite)
-- still has to land on a distinct, parseable document, and joining the parts
-- with dots made the name ambiguous the moment any of them contained one.
local mysql_buf = open("mysql", { schema = "shop" }, "orders")
check(
	"a nameless catalog is left out",
	vim.api.nvim_buf_get_name(mysql_buf),
	"neogrip://table/__test_detail__//shop/orders"
)
local sqlite_buf = open("sqlite", {}, "orders")
check(
	"and so is a nameless schema",
	vim.api.nvim_buf_get_name(sqlite_buf),
	"neogrip://table/__test_detail__///orders"
)
check("which is still a different buffer from the qualified one", sqlite_buf ~= mysql_buf, true)

vim.api.nvim_set_current_buf(origin)
for _, candidate in ipairs({ bufnr, mysql_buf, sqlite_buf }) do
	pcall(vim.api.nvim_buf_delete, candidate, { force = true })
end
