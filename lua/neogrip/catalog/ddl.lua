-- Render a table's definition from JDBC metadata. The rule the file is written
-- to: every non-comment line is runnable SQL; what JDBC cannot spell is said in a comment, never guessed.
local schema = require("neogrip.catalog")

local M = {}

-- Past this width, a foreign key's REFERENCES clause moves onto its own line.
local WIDTH = 100

-- ANSI identity is the default; Postgres, Oracle, DB2 and H2 all take it.
local IDENTITY = {
	mysql = "AUTO_INCREMENT",
	mariadb = "AUTO_INCREMENT",
	sqlite = "AUTOINCREMENT",
	mssql = "IDENTITY",
}

local function quote(driver, name)
	return schema.quote(driver, tostring(name))
end

local function quote_list(driver, names)
	local parts = {}
	for _, name in ipairs(names or {}) do
		parts[#parts + 1] = quote(driver, name)
	end
	return table.concat(parts, ", ")
end

--- A reported string, or nil when there is nothing in it. Flattened because a
--- multi-line value in a buffer line would raise; the string "nil" is how an
--- absent name reaches Lua from the Java side.
local function named(value)
	if value == nil then
		return nil
	end
	local text = vim.trim((tostring(value):gsub("%s+", " ")))
	if text == "" or text == "nil" then
		return nil
	end
	return text
end

--- A referential action, omitted when it is every engine's default "no action".
local function action(value)
	local text = named(value)
	if not text then
		return nil
	end
	local normal = text:lower()
	if normal == "no action" or normal == "none" or normal == "unknown" then
		return nil
	end
	return text:upper()
end

--- A SQL string literal, with the quote doubled as SQL doubles it.
local function literal(text)
	return "'" .. (tostring(text):gsub("'", "''")) .. "'"
end

--- An expression in exactly one pair of brackets: servers report a generation
--- expression both ways, and two pairs reads as a mistake.
local function grouped(expression)
	if expression:sub(1, 1) == "(" then
		local depth = 0
		for position = 1, #expression do
			local char = expression:sub(position, position)
			if char == "(" then
				depth = depth + 1
			elseif char == ")" then
				depth = depth - 1
				if depth == 0 then
					-- The group closes before the end, so "(a) + (b)" needs its own pair.
					return position == #expression and expression or ("(%s)"):format(expression)
				end
			end
		end
	end
	return ("(%s)"):format(expression)
end

--- The columns in declared order, sorted on a copy and only when every
--- position is a distinct number above zero: a driver that will not say
--- reports zero for all, and the unstable sort would shuffle a good order.
local function ordered(columns)
	local seen = {}
	for _, column in ipairs(columns) do
		local position = column.position
		if type(position) ~= "number" or position < 1 or seen[position] then
			return columns
		end
		seen[position] = true
	end
	local copy = vim.list_slice(columns, 1, #columns)
	table.sort(copy, function(left, right)
		return left.position < right.position
	end)
	return copy
end

--- One column of the CREATE TABLE, as { text, note }; the note carries what
--- the server reported too little of to spell as SQL.
local function column_entry(driver, column, widths)
	local parts = {
		("%-" .. widths.name .. "s %-" .. widths.type .. "s"):format(
			quote(driver, column.name),
			column.type or ""
		),
	}
	local note = nil

	if column.nullable == false or column.nullable == 0 then
		parts[#parts + 1] = "NOT NULL"
	end

	local default = named(column.default_expr)
	if column.auto_increment == true or column.auto_increment == 1 then
		-- A serial column's default and the identity clause say the same thing,
		-- so only one goes in.
		parts[#parts + 1] = IDENTITY[driver] or "GENERATED BY DEFAULT AS IDENTITY"
	elseif column.generated == true or column.generated == 1 then
		if default then
			parts[#parts + 1] = "GENERATED ALWAYS AS " .. grouped(default)
		else
			note = "generated"
		end
	elseif default then
		parts[#parts + 1] = "DEFAULT " .. default
	end

	return { text = vim.trim(table.concat(parts, " ")), note = note }
end

--- The declared keys, as named constraints where a name was reported.
local function constraints(connection, namespace, details)
	local driver = connection.driver
	local primary = details.primary_key or {}
	local keys = details.foreign_keys or {}
	local entries = {}

	local primary_name = named(details.primary_key_name)
	if primary_name == "PRIMARY" and (driver == "mysql" or driver == "mariadb") then
		-- MySQL's key name is unusable; see doc/internals.md#document-buffers.
		primary_name = nil
	end

	-- The constraint names align as a block of their own, read down it.
	local width = 1
	local names = {}
	if #primary > 0 then
		names[#names + 1] = primary_name
	end
	for _, key in ipairs(keys) do
		names[#names + 1] = named(key.name)
	end
	for _, name in ipairs(names) do
		width = math.max(width, #quote(driver, name))
	end

	local function head(name, keyword)
		if not name then
			return keyword
		end
		return ("CONSTRAINT %-" .. width .. "s %s"):format(quote(driver, name), keyword)
	end

	if #primary > 0 then
		entries[#entries + 1] = {
			text = ("%s (%s)"):format(head(primary_name, "PRIMARY KEY"), quote_list(driver, primary)),
		}
	end

	for _, key in ipairs(keys) do
		local target = ("REFERENCES %s (%s)"):format(
			schema.qualify(connection, key.schema or namespace, key.table),
			quote_list(driver, key.ref_columns)
		)
		local on_delete, on_update = action(key.on_delete), action(key.on_update)
		if on_delete then
			target = ("%s ON DELETE %s"):format(target, on_delete)
		end
		if on_update then
			target = ("%s ON UPDATE %s"):format(target, on_update)
		end

		local declaration = ("%s (%s)"):format(
			head(named(key.name), "FOREIGN KEY"),
			quote_list(driver, key.columns)
		)
		-- The comma is allowed for, so wrapping does not depend on being the last entry.
		if #declaration + #target + 6 <= WIDTH then
			entries[#entries + 1] = { text = ("%s %s"):format(declaration, target) }
		else
			entries[#entries + 1] = { text = declaration, continuation = target }
		end
	end

	return entries
end

--- The CREATE TABLE, from the columns and, unless told otherwise, the keys
--- they declare: an engine whose native text re-adds every constraint gets
--- the columns alone, or the replayed script would declare each key twice.
local function create_table(connection, namespace, table_name, details, keys)
	local driver = connection.driver
	local columns = ordered(details.rows or {})
	local lines = { ("CREATE TABLE %s ("):format(schema.qualify(connection, namespace, table_name)) }

	-- Names and types line up so a wide table reads down the column.
	local widths = { name = 1, type = 1 }
	for _, column in ipairs(columns) do
		widths.name = math.max(widths.name, #quote(driver, column.name))
		widths.type = math.max(widths.type, #tostring(column.type or ""))
	end

	local entries = {}
	for _, column in ipairs(columns) do
		entries[#entries + 1] = column_entry(driver, column, widths)
	end
	if keys ~= false then
		vim.list_extend(entries, constraints(connection, namespace, details))
	end

	for index, entry in ipairs(entries) do
		local tail = (index < #entries and "," or "") .. (entry.note and ("  -- " .. entry.note) or "")
		if entry.continuation then
			lines[#lines + 1] = "    " .. entry.text
			lines[#lines + 1] = "        " .. entry.continuation .. tail
		else
			lines[#lines + 1] = "    " .. entry.text .. tail
		end
	end
	lines[#lines + 1] = ");"
	return lines
end

--- The indexes, as the statements that would create them.
local function indexes(connection, namespace, table_name, details)
	local driver = connection.driver
	local qualified = schema.qualify(connection, namespace, table_name)
	local primary = table.concat(details.primary_key or {}, "\1")
	local lines = {}

	for _, index in ipairs(details.indexes or {}) do
		local columns = {}
		for position, column in ipairs(index.columns or {}) do
			local direction = tostring((index.order or {})[position] or ""):lower()
			columns[#columns + 1] = quote(driver, column) .. (direction == "desc" and " DESC" or "")
		end
		local spelled = table.concat(columns, ", ")

		-- An index implementing the primary key is already stated by the constraint.
		local implements_key = primary ~= "" and table.concat(index.columns or {}, "\1") == primary
		local name = named(index.name)

		local worth_writing = not implements_key and #columns > 0
		if worth_writing and not name then
			-- With no name there is no statement to write.
			lines[#lines + 1] = ("--   an unnamed %sindex on (%s)"):format(
				index.unique and "unique " or "",
				spelled
			)
		elseif worth_writing then
			local statement = ("CREATE %sINDEX %s ON %s (%s)"):format(
				index.unique and "UNIQUE " or "",
				quote(driver, name),
				qualified,
				spelled
			)
			local filter = named(index.filter)
			if filter then
				statement = ("%s WHERE %s"):format(statement, filter)
			end
			statement = statement .. ";"
			-- The kind is not shared syntax; see doc/internals.md#document-buffers.
			local kind = named(index.kind)
			if kind and kind ~= "other" then
				statement = ("%s  -- %s"):format(statement, kind)
			end
			lines[#lines + 1] = statement
		end
	end

	return lines
end

--- The remarks, as standard COMMENT ON; see doc/internals.md#document-buffers.
local function comments(connection, namespace, table_name, details)
	local driver = connection.driver
	local qualified = schema.qualify(connection, namespace, table_name)
	local lines = {}

	local remarks = named(details.remarks)
	if remarks then
		lines[#lines + 1] = ("COMMENT ON TABLE %s IS %s;"):format(qualified, literal(remarks))
	end
	for _, column in ipairs(details.rows or {}) do
		local note = named(column.remarks)
		if note then
			lines[#lines + 1] = ("COMMENT ON COLUMN %s.%s IS %s;"):format(
				qualified,
				quote(driver, column.name),
				literal(note)
			)
		end
	end

	return lines
end

--- What points at this table, as comments: a buffer you might yank out of
--- should not hand you statements that belong to another table.
local function annotations(connection, namespace, details)
	local driver = connection.driver
	local lines = {}

	local inbound = details.referenced_by or {}
	if #inbound > 0 then
		lines[#lines + 1] = ("-- Referenced by (%d)"):format(#inbound)
		for _, key in ipairs(inbound) do
			-- That table's column points at this table's column; an unnamed key
			-- must not leave trailing whitespace.
			lines[#lines + 1] = (
				("--   %s (%s) -> (%s)   %s")
					:format(
						schema.qualify(connection, key.schema or namespace, key.table),
						quote_list(driver, key.ref_columns),
						quote_list(driver, key.columns),
						named(key.name) or ""
					)
					:gsub("%s+$", "")
			)
		end
	end

	if #(details.indexes or {}) == 0 and #inbound == 0 and #(details.foreign_keys or {}) == 0 then
		-- Only reached when the block above wrote nothing, so no blank line of
		-- its own: one here would double the gap between sections.
		lines[#lines + 1] = "-- No indexes, foreign keys or inbound references reported."
		lines[#lines + 1] = "-- A query engine such as Trino has none to report."
	end

	return lines
end

--- The server's own DDL, verbatim, where it gave one: the two halves
--- disagreeing is the thing worth seeing, and a check constraint is only here.
local function native(details)
	local text = details.native_ddl
	if type(text) ~= "string" or vim.trim(text) == "" then
		return {}
	end
	local lines = { "-- As the server writes it" }
	for _, line in ipairs(vim.split(text, "\n", { plain = true })) do
		lines[#lines + 1] = (line:gsub("\r$", ""))
	end
	return lines
end

--- The CREATE TABLE alone, for a composition that brings its own constraints
--- and indexes (ADR-0047); `opts.keys = false` leaves the declared keys out.
--- @param opts table|nil { keys }
--- @return string[] lines
function M.create_table(connection, namespace, table_name, details, opts)
	if #(details.rows or {}) == 0 then
		return { ("-- %s: no columns reported"):format(tostring(table_name)) }
	end
	return create_table(connection, namespace, table_name, details, (opts or {}).keys)
end

--- The index statements alone, for the same composition.
--- @return string[] lines
function M.index_statements(connection, namespace, table_name, details)
	return indexes(connection, namespace, table_name, details)
end

--- The definition of one set, as lines of runnable SQL.
---
--- @param namespace string|nil the schema the set is in, when it has one
--- @return string[] lines
function M.details(connection, namespace, table_name, details)
	local columns = details.rows or {}
	if #columns == 0 then
		return { ("-- %s: no columns reported"):format(tostring(table_name)) }
	end
	-- One blank line between sections, decided here and nowhere else; trailing
	-- blanks are trimmed so the document never ends in whitespace.
	local lines = {}
	for _, section in ipairs({
		create_table(connection, namespace, table_name, details),
		indexes(connection, namespace, table_name, details),
		comments(connection, namespace, table_name, details),
		annotations(connection, namespace, details),
		native(details),
	}) do
		while #section > 0 and section[#section] == "" do
			table.remove(section)
		end
		if #section > 0 then
			if #lines > 0 then
				lines[#lines + 1] = ""
			end
			vim.list_extend(lines, section)
		end
	end
	return lines
end

return M
